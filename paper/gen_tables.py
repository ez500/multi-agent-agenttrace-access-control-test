#!/usr/bin/env python3
"""Generate LaTeX result-table fragments from the scenarios' aggregate.json.

Run after the experiments finish:
  python paper/gen_tables.py

Writes booktabs tabular bodies into paper/tables/*.tex, which the .tex paper
\\input{}s. Numbers therefore cannot drift from the data.

Two tables, and the split is deliberate. `arms.tex` is the OPERATING POINT:
attack detection paired with the benign false-halt rate on the same grid, so
no arm can look good on sensitivity alone. `cost.tex` is the PRICE: prompts,
tokens, dollars and judgment latency, which is what separates a free 5 ms
regex pass from a metered multi-second model call.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent / "tables"
OUT.mkdir(exist_ok=True)

SCENARIOS = {
    "scenario_1_external_incident": ("S1", "External incident"),
    "scenario_2_internal_incident": ("S2", "Internal incident"),
}
ARMS_ORDER = ["N", "A1", "A2", "B", "C"]
ARM_LABEL = {
    "N": "None",
    "A1": "Inv.\\ (det.)", "A2": "Inv.\\ (+cls.)",
    "B": "Sem.\\ proc.", "C": "Sem.\\ (aware)",
}


def _load(scn: str, name: str = "aggregate.json"):
    p = ROOT / scn / "results" / name
    return json.loads(p.read_text()) if p.exists() else None


def _ci(w):
    return f"[{w[0]:.2f}, {w[1]:.2f}]" if w else "--"


def _secs(ms: float) -> str:
    """Latency in whichever unit keeps it readable; the arms differ by three
    orders of magnitude, so one fixed unit would print either 0.0 or 9000."""
    if ms < 1000:
        return f"{ms:.0f}\\,ms"
    return f"{ms / 1000:.1f}\\,s"


def arms_table() -> str:
    """Detection paired with false halts: the operating point, not a rate."""
    rows = []
    for scn, (tag, title) in SCENARIOS.items():
        agg = _load(scn)
        ctl = _load(scn, "aggregate_control.json")
        if not agg:
            continue
        rows.append(f"    \\multicolumn{{6}}{{l}}{{\\emph{{{title}}}}} \\\\")
        for arm in ARMS_ORDER:
            v = agg["by_arm"].get(arm)
            if not v or v["n"] == 0:
                continue
            c = (ctl or {}).get("by_arm", {}).get(arm)
            if c and c["n"]:
                fp = f"{c['detected']}/{c['n']}"
                bal = (v["detect_rate"] + (1 - c["detected"] / c["n"])) / 2
                bal_s = f"{bal:.2f}"
            else:
                fp, bal_s = "--", "--"
            rows.append(
                f"    {ARM_LABEL[arm]} & {v['evaded']}/{v['n']} & "
                f"{_ci(v['evasion_wilson95'])} & "
                f"{v['detected']}/{v['n']} & {fp} & {bal_s} \\\\")
        rows.append("    \\addlinespace")
    body = "\n".join(rows)
    return (
        "% auto-generated by paper/gen_tables.py -- do not edit\n"
        "\\setlength{\\tabcolsep}{3.5pt}\n"
        "\\begin{tabular}{lccccc}\n\\toprule\n"
        "Arm & evaded & 95\\% CI & detect. & false halt & bal. \\\\\n"
        "\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n")


def cost_table() -> str:
    """Defense-side price and judgment latency.

    Leads with the two deterministic arms as the zero-cost reference line,
    then the semantic monitor under each trigger policy, then the garbage-flood
    condition where the trigger policy actually bites."""
    def _row(label, agg, arm, show_evas=True):
        v = agg["by_arm"].get(arm) if agg else None
        if not v:
            return None
        evas = f"{v['evasion_rate']:.2f}" if show_evas else "--"
        return (f"    {label} & {v['mean_prompts']:.1f} & "
                f"{v['mean_defense_tokens']:.0f} & {v['mean_defense_usd']:.4f} & "
                f"{_secs(v['latency_p50_ms'])} & {_secs(v['latency_p95_ms'])} & "
                f"{evas} \\\\")
    rows = []
    scn2 = "scenario_2_internal_incident"
    for lab, arm in (("Invariant (det.)", "A1"), ("Invariant (+cls.)", "A2")):
        r = _row(lab, _load(scn2), arm)
        if r:
            rows.append(r)
    for scn, (tag, title) in SCENARIOS.items():
        if tag != "S2":
            continue
        r1 = _row("Semantic, per-event", _load(scn), "B")
        r2 = _row("Semantic, time-based", _load(scn, "aggregate_timebased.json"), "B")
        if r1:
            rows.append(r1)
        if r2:
            rows.append(r2)
    fpe = _load(scn2, "aggregate_flood_perevent.json")
    ftb = _load(scn2, "aggregate_flood_timebased.json")
    for lab, agg in (("Flood, per-event", fpe),
                     ("Flood, time-based", ftb)):
        r = _row(lab, agg, "C")
        if r:
            rows.append(r)
    body = "\n".join(rows) or "    \\multicolumn{7}{l}{(pending runs)} \\\\"
    return (
        "% auto-generated by paper/gen_tables.py -- do not edit\n"
        "\\setlength{\\tabcolsep}{3.5pt}\n"
        "\\begin{tabular}{lcccccc}\n\\toprule\n"
        "Condition & prompts & tokens & \\$/run & $p_{50}$ & $p_{95}$ & evas. \\\\\n"
        "\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n")


def facts() -> str:
    """Numbers the prose quotes, as \\newcommand macros, so a sentence in the
    body cannot drift from the run data either."""
    s2 = _load("scenario_2_internal_incident")
    s1 = _load("scenario_1_external_incident")
    out = ["% auto-generated by paper/gen_tables.py -- do not edit"]

    def macro(name, val):
        out.append(f"\\newcommand{{\\{name}}}{{{val}}}")

    if s2:
        a1 = s2["by_arm"]["A1"]
        b = s2["by_arm"]["B"]
        macro("SIIn", a1["n"])
        macro("SIIdetEvaded", a1["evaded"])
        macro("SIIdetRate", f"{a1['evasion_rate']:.2f}")
        macro("SIIdetCI", f"[{a1['evasion_wilson95'][0]:.2f}, {a1['evasion_wilson95'][1]:.2f}]")
        macro("SIIsemN", b["n"])
        macro("SIIsemCI", f"[{b['evasion_wilson95'][0]:.2f}, {b['evasion_wilson95'][1]:.2f}]")
        n = s2["by_arm"].get("N")
        if n:
            macro("SIInoDefN", n["n"])
            macro("SIInoDefEvaded", n["evaded"])
            macro("SIInoDefCI", f"[{n['evasion_wilson95'][0]:.2f}, {n['evasion_wilson95'][1]:.2f}]")
    if s1:
        n1 = s1["by_arm"].get("N")
        if n1:
            macro("SInoDefN", n1["n"])
            macro("SInoDefEvaded", n1["evaded"])
        macro("SIn", s1["by_arm"]["B"]["n"])
    fl = _load("scenario_2_internal_incident", "aggregate_flood_perevent.json")
    if fl:
        macro("FloodN", fl["by_arm"]["C"]["n"])
    ctl = _load("scenario_2_internal_incident", "aggregate_control.json")
    if ctl:
        macro("BenignN", ctl["by_arm"]["B"]["n"])
        w = ctl["by_arm"]["B"]["detect_wilson95"]
        macro("BenignUpper", f"{w[1]:.2f}")
    return "\n".join(out) + "\n"


def main() -> int:
    import subprocess
    subprocess.run([sys.executable, str(Path(__file__).parent / "reaggregate.py")], check=False)
    (OUT / "arms.tex").write_text(arms_table())
    (OUT / "cost.tex").write_text(cost_table())
    (OUT / "facts.tex").write_text(facts())
    stale = OUT / "token_efficiency.tex"
    if stale.exists():
        stale.unlink()
    stale = OUT / "fpr.tex"
    if stale.exists():
        stale.unlink()
    print("wrote:", *[p.name for p in sorted(OUT.glob("*.tex"))])
    return 0


if __name__ == "__main__":
    sys.exit(main())
