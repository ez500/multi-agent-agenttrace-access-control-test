#!/usr/bin/env python3
"""Generate LaTeX result-table fragments from the scenarios' aggregate.json.

Run after the experiments finish:
  python paper/gen_tables.py

Writes booktabs tabular bodies into paper/tables/*.tex, which the .tex paper
\\input{}s. Numbers therefore cannot drift from the data.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = Path(__file__).resolve().parent / "tables"
OUT.mkdir(exist_ok=True)

SCENARIOS = {
    "scenario_1_external_incident": ("S1", "External incident"),
    "scenario_2_internal_incident": ("S2", "Internal incident"),
}
ARMS_ORDER = ["A1", "A2", "B", "C"]
ARM_LABEL = {
    "A1": "Invariant (det.)", "A2": "Invariant (+cls.)",
    "B": "Log proc. (sem.)", "C": "Log proc. (aware)",
}


def _load(scn: str, name: str = "aggregate.json"):
    p = ROOT / scn / "results" / name
    return json.loads(p.read_text()) if p.exists() else None


def _ci(w):
    return f"[{w[0]:.2f}, {w[1]:.2f}]" if w else "--"


def arms_table() -> str:
    rows = []
    for scn, (tag, title) in SCENARIOS.items():
        agg = _load(scn)
        if not agg:
            continue
        rows.append(f"    \\multicolumn{{7}}{{l}}{{\\emph{{{title}}}}} \\\\")
        for arm in ARMS_ORDER:
            v = agg["by_arm"].get(arm)
            if not v or v["n"] == 0:
                continue
            rows.append(
                f"    {ARM_LABEL[arm]} & {v['evaded']} & {v['resolved']} & "
                f"{v['no_incident']} & {v['evasion_rate']:.2f} & "
                f"{v['mean_prompts']:.1f} & {v['mean_defense_usd']:.4f} \\\\")
        rows.append("    \\addlinespace")
    body = "\n".join(rows)
    return (
        "% auto-generated by paper/gen_tables.py -- do not edit\n"
        "\\begin{tabular}{lcccccc}\n\\toprule\n"
        "Arm & evad. & resol. & no-inc. & evas.\\ rate & prompts & \\$/run \\\\\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n")


def token_table() -> str:
    """Per-event vs time-based, arm B, both scenarios."""
    rows = []
    for scn, (tag, title) in SCENARIOS.items():
        pe = _load(scn)
        tb = _load(scn, "aggregate_timebased.json")
        b_pe = pe["by_arm"].get("B") if pe else None
        b_tb = tb["by_arm"].get("B") if tb else None
        if b_pe:
            rows.append(f"    {title} & per-event & {b_pe['mean_prompts']:.1f} & "
                        f"{b_pe['mean_defense_tokens']:.0f} & {b_pe['mean_defense_usd']:.4f} \\\\")
        if b_tb:
            rows.append(f"    {title} & time-based & {b_tb['mean_prompts']:.1f} & "
                        f"{b_tb['mean_defense_tokens']:.0f} & {b_tb['mean_defense_usd']:.4f} \\\\")
    body = "\n".join(rows) or "    \\multicolumn{5}{l}{(pending runs)} \\\\"
    return (
        "% auto-generated by paper/gen_tables.py -- do not edit\n"
        "\\begin{tabular}{llccc}\n\\toprule\n"
        "Scenario & trigger & prompts & def.\\ tokens & \\$/run \\\\\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n")


def fpr_table() -> str:
    rows = []
    for scn, (tag, title) in SCENARIOS.items():
        agg = _load(scn, "aggregate_control.json")
        if not agg:
            continue
        rows.append(f"    \\multicolumn{{3}}{{l}}{{\\emph{{{title}}}}} \\\\")
        for arm in ARMS_ORDER:
            v = agg["by_arm"].get(arm)
            if not v or v["n"] == 0:
                continue
            # On benign runs, any neutralize is a false positive.
            fp = v["resolved"]   # resolved on a benign run == a spurious halt
            rows.append(f"    {ARM_LABEL[arm]} & {fp}/{v['n']} & "
                        f"{fp / v['n']:.2f} \\\\")
        rows.append("    \\addlinespace")
    body = "\n".join(rows) or "    \\multicolumn{3}{l}{(pending control runs)} \\\\"
    return (
        "% auto-generated by paper/gen_tables.py -- do not edit\n"
        "\\begin{tabular}{lcc}\n\\toprule\n"
        "Arm & false halts & FPR \\\\\n\\midrule\n"
        f"{body}\n\\bottomrule\n\\end{{tabular}}\n")


def main() -> int:
    (OUT / "arms.tex").write_text(arms_table())
    (OUT / "token_efficiency.tex").write_text(token_table())
    (OUT / "fpr.tex").write_text(fpr_table())
    print("wrote:", *[p.name for p in OUT.glob("*.tex")])
    return 0


if __name__ == "__main__":
    sys.exit(main())
